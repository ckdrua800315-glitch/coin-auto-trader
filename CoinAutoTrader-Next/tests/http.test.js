import {test} from 'node:test';
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import net from 'node:net';
import {root} from '../src/config.js';
test('HTTP authentication, origin protection, CSV, restart and duplicate-process lock',async t=>{
  const dir=fs.mkdtempSync(path.join(os.tmpdir(),'harbor-http-'));
  const probe=net.createServer();await new Promise(r=>probe.listen(0,'127.0.0.1',r));const port=probe.address().port;await new Promise(r=>probe.close(r));
  const url=`http://127.0.0.1:${port}`;let child,launchError='',lastConnectError='';
  const launch=()=>{const c=spawn(process.execPath,['src/server.js'],{cwd:root,env:{...process.env,DATA_DIR:dir,PORT:String(port),HOST:'127.0.0.1'},stdio:'pipe'});c.stderr.on('data',b=>{launchError+=b.toString();});c.stdout.on('data',b=>{launchError+=b.toString();});return c;};
  const stop=async()=>{if(!child||child.exitCode!==null)return;const done=new Promise(r=>child.once('exit',r));child.kill();await done;};
  t.after(async()=>{await stop();fs.rmSync(dir,{recursive:true,force:true});});
  const wait=async()=>{for(let i=0;i<100;i++){try{if((await fetch(url+'/health')).ok)return;}catch(e){lastConnectError=String(e.cause||e);}await new Promise(r=>setTimeout(r,50));}throw Error('Startup timeout: '+launchError+'; connection: '+lastConnectError);};
  child=launch();await wait();
  const token=fs.readFileSync(path.join(dir,'access-token.txt'),'utf8').trim(),headers={Authorization:'Bearer '+token,'Content-Type':'application/json'};
  assert.equal((await fetch(url+'/api/state')).status,401);
  const html=await(await fetch(url)).text();assert.ok(html.includes('PAPER ONLY'));assert.ok(!html.includes(token));
  assert.equal((await fetch(url+'/api/control',{method:'POST',headers:{...headers,Origin:'https://evil.example'},body:'{"action":"pause"}'})).status,403);
  assert.equal((await fetch(url+'/api/control',{method:'POST',headers,body:'{"action":"pause"}'})).status,200);
  assert.equal((await(await fetch(url+'/api/state',{headers})).json()).state.paused,true);
  assert.equal((await fetch(url+'/api/control',{method:'POST',headers,body:'{"action":"live"}'})).status,400);
  assert.ok((await(await fetch(url+'/api/trades.csv',{headers})).text()).includes('id,at,exchange,market,side,price,qty,fee,pnl,reason'));
  const duplicate=launch();const exitCode=await new Promise(r=>duplicate.once('exit',r));assert.notEqual(exitCode,0);
  await stop();child=launch();await wait();
  assert.equal(fs.readFileSync(path.join(dir,'access-token.txt'),'utf8').trim(),token);
  const restored=await(await fetch(url+'/api/state',{headers})).json();assert.equal(restored.state.paused,true);assert.equal(restored.mode,'paper');
});
